void verifySeat(const Settings& settings) {
    // Diameter-340 caps, two quarter-torus fillets of developed width 19,
    // and a 6-mm-high cylinder. Face boundaries share exact model vertices.
    const int segments=72, rows=4;
    const double capRadius=170, filletRadius=19/(tau/4), outerRadius=capRadius+filletRadius;
    std::vector<Triangle> mesh;
    std::vector<FaceInput> faces;
    auto point=[](int i,double radius,double z) {
        const double u=tau*(i%segments)/segments;
        return Point{radius*std::cos(u),radius*std::sin(u),z};
    };
    for(int side=0;side<2;++side) {
        const double centerZ=side==0?6:0, direction=side==0?1:-1;
        const double z=centerZ+direction*filletRadius;
        const int first=int(mesh.size());
        for(int i=0;i<segments;++i)
            mesh.push_back({{Point{0,0,z},point(i,capRadius,z),point(i+1,capRadius,z)}});
        faces.push_back({0,first,segments,false,{0,0,z,0,0,1,1,0,0},1e-7,{1,0,0}});
        const int filletFirst=int(mesh.size());
        auto surface=[&](int i,int j) {
            // Exact endpoints make the face-boundary census independent of roundoff.
            if(j==0) return point(i,outerRadius,centerZ);
            if(j==rows) return point(i,capRadius,z);
            double v=(tau/4)*j/rows;
            return point(i,capRadius+filletRadius*std::cos(v),centerZ+direction*filletRadius*std::sin(v));
        };
        for(int i=0;i<segments;++i) for(int j=0;j<rows;++j) {
            auto a=surface(i,j),b=surface(i+1,j),c=surface(i+1,j+1),d=surface(i,j+1);
            mesh.push_back({{a,b,c}});mesh.push_back({{a,c,d}});
        }
        faces.push_back({2,filletFirst,2*segments*rows,false,
                         {0,0,centerZ,0,0,1,1,0,0,capRadius,filletRadius},1e-7,{1,0,0}});
    }
    const int first=int(mesh.size());
    auto rim=band(segments,outerRadius,6);mesh.insert(mesh.end(),rim.begin(),rim.end());
    faces.push_back({1,first,int(rim.size()),false,{0,0,0,0,0,1,1,0,0,outerRadius},1e-7,{1,0,0}});
    const auto result=unwrap(mesh,faces,settings);
    if(!result.ok) std::printf("analytic seat rejected: %s\n",result.reason.c_str());
    check(result.ok,"five-face analytic seat admitted");
    if(!result.ok) return;
    check(result.atlas.chartCount<=12,"analytic seat <=12 charts");
    check(result.atlas.occupancy>=.45,"analytic seat A2 occupancy gate");
    // Simulate the exact decimal persistence of the live D5 frame/tolerance
    // inputs, then validate only the retained mesh/provenance on a cold copy.
    auto replayFaces=result.layout.regenerationFaces;
    std::stringstream frames;frames.imbue(std::locale::classic());frames<<std::setprecision(17);
    for(const auto& f:replayFaces)
        frames<<f.toleranceMM<<' '<<f.xDirection[0]<<' '<<f.xDirection[1]<<' '<<f.xDirection[2]<<'\n';
    for(auto& f:replayFaces) {
        f.toleranceMM=0;f.xDirection={};
        frames>>f.toleranceMM>>f.xDirection[0]>>f.xDirection[1]>>f.xDirection[2];
    }
    check(bool(frames) && validate(mesh,replayFaces,settings,result.atlas.corners),
          "seat persisted replay inputs accept unchanged UV copy");
    for(int axis=0;axis<2;++axis) {
        auto changed=result.atlas.corners;
        changed[682][1][axis]=std::nextafter(changed[682][1][axis],1.0);
        check(!validate(mesh,replayFaces,settings,changed),"seat one-ULP UV change rejected");
    }
    check(!validate(mesh,replayFaces,{settings.resolution,settings.gutterPixels-1},result.atlas.corners),
          "seat changed gutter does not validate stored UVs");
    check(result.layout.faces.size()==5,"analytic seat face census");
    check(result.layout.tornEdges==0 && result.layout.diagonalSeamEdges==0,"analytic seat zero tears/diagonal seams");
    const auto& census=result.coverage.seamCounts;
    check(census.declared==census.kernelSeamEdges+census.splitSeamEdges,"analytic seat declared = kernel + split");
    // Four cap/fillet/rim boundaries, plus the two fillet U cuts (one
    // edge per row) and the rim U cut. Whole-turn canonicalization removes
    // the artificial lower-fillet V branch; it is an open quarter-band.
    check(census.kernelSeamEdges==4*segments+2*rows+1,
          "source boundaries plus analytic periodic grid cuts");
    check(census.continuous+census.declared==long(mesh.size())*3/2,"closed seat complete shared-edge census");
    int charts=0;long seams=0;
    for(const auto& f:result.layout.faces) { charts+=f.subChartCount;seams+=f.seamCount;
        check(f.kernel!=curveduv::KernelTag::Fallback,"seat uses analytic kernels"); }
    check(charts==result.atlas.chartCount,"per-face fitted chart totals agree");
    check(seams==census.declared+4*segments,"source-face boundary counted once globally and in both faces");
    std::printf("analytic seat: charts=%d occupancy=%.8f density=%.8f kernel=%ld split=%ld diagonal=%ld torn=%ld\n",
                result.atlas.chartCount,result.atlas.occupancy,result.layout.globalTexelsPerMM,
                census.kernelSeamEdges,census.splitSeamEdges,census.diagonalSeamEdges,census.torn);
}
void verifyDensity(const std::vector<Triangle>& input,const Result& value) {
    // Torus edge lengths independently obtained from atan2 and the analytic
    // developed metric; both directions share precisely the stored global s.
    double s=value.layout.globalTexelsPerMM/1024;
    bool good=true;
    for(std::size_t t=0;t<input.size();++t) for(int k=0;k<3;++k) {
        auto p=input[t].points[k],q=input[t].points[(k+1)%3];
        double du=std::remainder(std::atan2(q[1],q[0])-std::atan2(p[1],p[0]),tau);
        double dv=std::remainder(std::atan2(q[2],std::hypot(q[0],q[1])-208.8)-std::atan2(p[2],std::hypot(p[0],p[1])-208.8),tau);
        auto a=value.atlas.corners[t][k],b=value.atlas.corners[t][(k+1)%3];
        good=good && std::abs(std::hypot(a[0]-b[0],a[1]-b[1])-s*std::hypot(208.8*du,5.9*dv))<1.e-10;
    }
    check(good,"independent torus edge metric uses one global density");
}
